// Generates src/infrastructure/api/schema.d.ts from the backend OpenAPI document.
// Usage: node scripts/contract/api-types.mjs <generate|check>
// BACKEND_URL names the backend. The default is http://localhost:3000.
// "generate" writes the file. "check" writes a temp copy and fails when it differs.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const schemaPath = 'src/infrastructure/api/schema.d.ts';
const schemaFile = path.join(repoRoot, schemaPath);
const backendUrl = process.env.BACKEND_URL ?? 'http://localhost:3000';
const documentUrl = new URL('docs-json', backendUrl.endsWith('/') ? backendUrl : `${backendUrl}/`);

const header =
  '// Generated by `pnpm api:generate` from the backend OpenAPI document. Do not edit.\n\n';

async function renderTypes() {
  try {
    return header + astToString(await openapiTS(documentUrl));
  } catch (error) {
    console.error(`Cannot read the OpenAPI document at ${documentUrl}: ${error.message}`);
    console.error('Start the backend or set BACKEND_URL.');
    process.exit(1);
  }
}

async function generate() {
  await writeFile(schemaFile, await renderTypes());
  console.log(`Wrote ${schemaPath} from ${documentUrl}`);
}

async function check() {
  const fresh = await renderTypes();
  const tempDir = await mkdtemp(path.join(os.tmpdir(), 'api-check-'));
  const tempFile = path.join(tempDir, 'schema.d.ts');
  try {
    await writeFile(tempFile, fresh);
    const committed = await readFile(schemaFile, 'utf8').catch(() => '');
    if (committed === fresh) {
      console.log(`${schemaPath} matches ${documentUrl}`);
      return;
    }
    spawnSync('git', ['--no-pager', 'diff', '--no-index', '--', schemaFile, tempFile], {
      stdio: 'inherit',
    });
    console.error(`${schemaPath} differs from the backend OpenAPI document at ${documentUrl}.`);
    console.error('Run pnpm api:generate against that backend and commit the result.');
    process.exitCode = 1;
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

const modes = { generate, check };
const mode = modes[process.argv[2]];
if (mode === undefined) {
  console.error('Usage: node scripts/contract/api-types.mjs <generate|check>');
  process.exit(2);
}
await mode();
