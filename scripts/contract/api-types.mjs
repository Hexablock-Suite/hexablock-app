// Generates the API types from the backend OpenAPI document (classes.md decision 22, option A3).
// Usage: node scripts/contract/api-types.mjs <generate|check>
// BACKEND_URL names the backend. The default is http://localhost:3000.
// It splits the output into two files:
// - src/adapters/api/dto.d.ts holds the DTO schemas, so layer 3 owns the DTO types.
// - src/infrastructure/api/schema.d.ts holds the paths and the operations, and it imports the DTOs.
// "generate" writes both files. "check" writes temp copies and fails when one of them differs.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dtoPath = 'src/adapters/api/dto.d.ts';
const schemaPath = 'src/infrastructure/api/schema.d.ts';
const backendUrl = process.env.BACKEND_URL ?? 'http://localhost:3000';
const documentUrl = new URL('docs-json', backendUrl.endsWith('/') ? backendUrl : `${backendUrl}/`);

const header =
  '// Generated by `pnpm api:generate` from the backend OpenAPI document. Do not edit.\n\n';
const dtoImport = "import type { components } from '../../adapters/api/dto';\n\n";
const componentsStart = 'export interface components {';

async function renderTypes() {
  try {
    return astToString(await openapiTS(documentUrl));
  } catch (error) {
    console.error(`Cannot read the OpenAPI document at ${documentUrl}: ${error.message}`);
    console.error('Start the backend or set BACKEND_URL.');
    process.exit(1);
  }
}

// Splits the generated types into the text of each file.
// The `components` interface ends at the first closing brace in column 0 after its start.
// A document with no schemas still gives a `components` interface, with `schemas: never`.
function splitTypes(types) {
  const start = types.indexOf(componentsStart);
  const end = start < 0 ? -1 : types.indexOf('\n}\n', start);
  if (end < 0) {
    console.error('The generated types hold no components interface.');
    process.exit(1);
  }
  const close = end + '\n}\n'.length;
  return [
    { file: dtoPath, text: header + types.slice(start, close) },
    { file: schemaPath, text: header + dtoImport + types.slice(0, start) + types.slice(close) },
  ];
}

async function generate() {
  for (const { file, text } of splitTypes(await renderTypes())) {
    await writeFile(path.join(repoRoot, file), text);
    console.log(`Wrote ${file} from ${documentUrl}`);
  }
}

async function check() {
  const fresh = splitTypes(await renderTypes());
  const tempDir = await mkdtemp(path.join(os.tmpdir(), 'api-check-'));
  try {
    let differs = false;
    for (const { file, text } of fresh) {
      const committedFile = path.join(repoRoot, file);
      const committed = await readFile(committedFile, 'utf8').catch(() => '');
      if (committed === text) {
        console.log(`${file} matches ${documentUrl}`);
        continue;
      }
      const tempFile = path.join(tempDir, path.basename(file));
      await writeFile(tempFile, text);
      spawnSync('git', ['--no-pager', 'diff', '--no-index', '--', committedFile, tempFile], {
        stdio: 'inherit',
      });
      console.error(`${file} differs from the backend OpenAPI document at ${documentUrl}.`);
      differs = true;
    }
    if (differs) {
      console.error('Run pnpm api:generate against that backend and commit the result.');
      process.exitCode = 1;
    }
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

const modes = { generate, check };
const mode = modes[process.argv[2]];
if (mode === undefined) {
  console.error('Usage: node scripts/contract/api-types.mjs <generate|check>');
  process.exit(2);
}
await mode();
